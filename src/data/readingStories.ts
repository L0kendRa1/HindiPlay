/**
 * Generates a round of stories for the given difficulty.
 */
export function generateReadingRound(
  difficulty: StoryDifficulty = 'easy',
  count = 5
): StoryData[] {
  const pool = HINDI_STORIES.filter((s) => s.difficulty === difficulty);
  const shuffled = shuffleArray(pool);
  return shuffled.slice(0, Math.min(count, shuffled.length));
}
